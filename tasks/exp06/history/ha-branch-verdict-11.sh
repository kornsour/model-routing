cat > scripts/deploy-aws.sh <<'EOF'
#!/usr/bin/env bash
# Deploys packlight to AWS: builds the standalone server, syncs static assets to
# S3 and rolls the ECS service. Replaces the Vercel deploy (see docs/deploy.md).
set -euo pipefail
stage="${1:?usage: deploy-aws.sh <staging|production>}"
pnpm build
aws s3 sync .next/static "s3://packlight-${stage}-static/_next/static" --delete
aws ecs update-service --cluster "packlight-${stage}" --service web --force-new-deployment
EOF
chmod +x scripts/deploy-aws.sh
