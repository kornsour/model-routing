#!/usr/bin/env bash
# Builds packlight's history for ha-branch-verdict-11: feat/aws-staging is one
# commit of SST scaffolding off an old main; main has since moved 11 commits on,
# including a script-based AWS deploy. Runs inside the sandbox after its first
# commit. Deterministic: fixed identities and dates.
set -euo pipefail
# The sandbox's first commit carries today's date; back-date it so the history
# below is never older than its own root (clock skew breaks `git rev-list A..B`).
GIT_COMMITTER_DATE="2026-07-01T09:00:00Z" git -c user.name=sandbox -c user.email=sandbox@local \
  commit -q --amend --no-edit --date="2026-07-01T09:00:00Z"
export GIT_AUTHOR_NAME="Packlight Dev" GIT_AUTHOR_EMAIL="dev@packlight.example"
export GIT_COMMITTER_NAME="Packlight Dev" GIT_COMMITTER_EMAIL="dev@packlight.example"
n=0
commit() { # commit <message>; dates step a day from 2026-09-01
  n=$((n + 1))
  GIT_AUTHOR_DATE="2026-09-$(printf %02d $((n < 29 ? n : 28)))T10:00:00Z"
  export GIT_AUTHOR_DATE GIT_COMMITTER_DATE="$GIT_AUTHOR_DATE"
  git add -A && git commit -q -m "$1"
}
git branch -M main

# --- the branch: SST scaffolding only, off the first commit ---
git switch -q -c feat/aws-staging
cat > sst.config.ts <<'EOF'
/// <reference path="./.sst/platform/config.d.ts" />
export default $config({
  app(input) {
    return { name: "packlight", home: "aws", removal: input?.stage === "production" ? "retain" : "remove" };
  },
  async run() {
    new sst.aws.Nextjs("Web", { environment: { DATABASE_URL: process.env.DATABASE_URL ?? "" } });
  },
});
EOF
cat > sst-env.d.ts <<'EOF'
/* This file is auto-generated by SST. Do not edit. */
/* deno-fmt-ignore-file */
import "sst"
export {}
declare module "sst" {
  export interface Resource {
    "Web": { "type": "sst.aws.Nextjs"; "url": string }
  }
}
EOF
mkdir -p .github/workflows
cat > .github/workflows/aws-staging.yml <<'EOF'
name: AWS staging
on:
  push:
    branches: [feat/aws-staging]
permissions:
  contents: read
  id-token: write
jobs:
  deploy:
    runs-on: ubuntu-latest
    environment: staging
    steps:
      - uses: actions/checkout@08eba0b27e820071cde6df949e0beb9ba4906955 # v4.3.0
      - run: pnpm install --frozen-lockfile
      - run: pnpm sst deploy --stage staging
EOF
commit "feat: AWS staging environment via SST"

# --- main moves on: 11 commits ---
git switch -q main
cat >> src/lib/trips.ts <<'EOF'

export function tripLengthDays(trip: Trip): number {
	return Math.round((Date.parse(trip.end) - Date.parse(trip.start)) / 86_400_000) + 1;
}
EOF
